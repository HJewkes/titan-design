// The 45 visual types the router can name, with honest build status and the closest
// available fallback for each gap. The type list and the "not this, use that" idea come
// from cathrynlavery/diagram-design (MIT, (c) 2025 Cathryn Lavery); all wording,
// budgets and titan mappings here are titan's own.
import type { TypeId, TypeStatus, VisualType } from './types'

type Build = Pick<VisualType, 'status' | 'component' | 'storyId'>

function storyIdOf(title: string): string {
  return `${title.toLowerCase().replace(/\//g, '-')}--default`
}

function have(component: string, storyTitle: string): Build {
  return { status: 'have', component, storyId: storyIdOf(storyTitle) }
}

function gap(status: Exclude<TypeStatus, 'have'>): Build {
  return { status, component: null, storyId: null }
}

