// Synthetic active-work state (initiatives, tasks, sessions) in the shape
// tools/export-aw-data.mjs emits. Never commit a real export here: this package is public.

export type InitiativeState = 'focused' | 'backburner' | 'paused' | 'done'
export type TaskSeverity = 'critical' | 'high' | 'medium' | 'low'
export type TaskStatus = 'open' | 'done'

export interface InitiativeSummary {
  slug: string
  title: string
  state: InitiativeState
  rank?: number
  ship_target?: string
  paused_since?: string
  updated: string
}
export interface InitiativeSection {
  heading: string
  items: InitiativeSummary[]
}

export interface AwTask {
  id: string
  slug: string
  title: string
  priority: number
  severity?: TaskSeverity
  estimate?: number
  status: TaskStatus
  done_when?: string
  tags?: string[]
  notes?: string
  created: string
  updated: string
  done_at?: string | null
}

export interface AwSession {
  filename: string
  session_id: string
  started: string
  ended: string
  track: string
  first_line: string
  body: string
}

export interface AwData {
  generatedNote: string
  sections: InitiativeSection[]
  parseErrors: { slug: string; error: string }[]
  tasks: AwTask[]
  focus: {
    slug: string
    brief: InitiativeSummary | null
    briefBody: string
    handoffBody: string
    sessions: AwSession[]
  }
}

